//! Translating the Rust compiler's diagnostics back to `.rsx` positions
//! (issue #25, A5; `docs/backend-leakage.md` row 39).
//!
//! `cargo` reports an error in `.rsx` code at `src/.generated/<file>.rs`,
//! a file nobody wrote. This module is the one place that turns such a
//! diagnostic into an Outou diagnostic: it is used by `outou cargo`
//! ([`crate::cargo`]) and by the UI test harness
//! (`crates/outou-cli/tests/ui.rs`), so "there is one compiler"
//! (`AGENTS.md`) holds for the semantic layers too.
//!
//! Split by job:
//!
//! - [`parse`]: `cargo --message-format=json` lines into plain structs.
//! - [`locate`]: a generated byte span to a `.rsx` span through a
//!   [`outou_sourcemap::SourceMap`] (narrow, then coarse, then nearest).
//! - [`translate`]: one compiler message to a [`translate::Translated`]
//!   diagnostic, applying the documented rules for what cannot be
//!   translated.
//! - [`resolve`]: finding the source map of a generated file on disk.
//! - [`render`]: the text `outou cargo` prints.
//! - `sanitize`: generated paths and backend vocabulary in prose.
//! - `twin`: the twin filter and the error-code notes.
//!
//! # Rules for what cannot be translated
//!
//! These are the rules, in the order they apply. They are also stated in
//! `crates/outou-cli/README.md`.
//!
//! 1. **Generated file with a source map**: the primary span is mapped to
//!    the `.rsx` file, line and column ([`locate::map_generated_span`]).
//! 2. **A span that covers 15 or more lines** (the whole body Dioxus
//!    sees, for example): narrowed as a whole first, and kept when that
//!    is exact; otherwise only its start is mapped, so the diagnostic
//!    points at the start of the nearest element or statement instead of
//!    a range that does not exist in the `.rsx` file
//!    ([`locate::COARSE_SPAN_LINES`]).
//! 3. **No mapping at the span** (synthesized code, for example the
//!    `{}` of a numeric child): the nearest mapped position is used,
//!    never dropping a hard error.
//! 4. **Secondary spans** are kept as notes only when they map exactly
//!    (verbatim) into a `.rsx` file; everything else is dropped.
//!    Spans that carry a macro expansion, and so point at the backend's
//!    macro definition, are always dropped (they are leakage). A child
//!    `note:` / `help:` with such a span, or with a span outside the
//!    workspace, is dropped whole.
//! 5. **Suggested replacements** are shown (`replace`, `insert` or
//!    `remove`) only when the generated text under the span is byte for
//!    byte the text of the `.rsx` span it maps to; otherwise only the
//!    message is kept.
//! 6. **Plain `.rs` files** (`src/.generated/../state.rs`, a module
//!    reached through `#[path]`) need no map: the path is normalised and
//!    the diagnostic is printed as rustc rendered it, unless that
//!    rendering shows a dependency, a macro expansion or backend
//!    vocabulary, in which case it is rendered from the workspace spans.
//! 7. **A generated file whose map cannot be read**: the message is
//!    kept, its location is dropped, so no `.generated` path is printed.
//! 8. **Backend vocabulary** in a message, label or note is translated
//!    ([`outou_syntax::vocabulary::translate_message`]); a label or note
//!    that would need translating is dropped instead, since it repeats
//!    the message. Every text also loses generated paths ([`sanitize`]).
//! 9. **The untranslated twin of a missing-prop diagnostic** (`E0061`
//!    with a `Missing_required_field` label, same generated range) is
//!    dropped ([`translate::suppress_untranslated_duplicates`] for a
//!    batch, [`translate::TwinFilter`] for the stream `outou cargo`
//!    prints; one implementation). The notes that list error codes then
//!    name only the codes shown ([`translate::ExplanationNotes`]).
//! 10. **The trait helps around a JSX child diagnostic** (issue #27). Under a
//!     message ending in "cannot be rendered as a JSX child", a help that
//!     `Iterator` is not implemented for the type is dropped (for a `Vec` it
//!     becomes "a `Vec` is not an iterator; use `.into_iter()`"). Current
//!     rustc no longer prints that help (the facade's `on_unimplemented`
//!     note carries the hint), so this is kept for older output. A
//!     `Vec<Result<VNode, RenderError>>` is first named `Vec<Element>`
//!     so the message is not mistaken for backend vocabulary. Under any
//!     message, a note or help that names `IntoChild<..>` (the list of
//!     implementing types, `required for .. to implement
//!     IntoChild<..Delegated<_>>`) is dropped. They describe the facade's
//!     implementation, not the mistake.

