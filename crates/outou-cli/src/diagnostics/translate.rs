    const MISSING_FIELD_LABEL: &str =
        "argument #1 of type `GreetingPropsBuilder_Error_Missing_required_field_name` is missing";

    /// A diagnostic whose primary span is generated bytes `start..end`.
    fn at(text: &str, label: Option<&str>, start: u32, end: u32) -> Translated {
        let mut primary = span_json("src/.generated/a.rs", start, end, true, "");
        if let Some(label) = label {
            primary = primary.replace(r#""label":null"#, &format!(r#""label":"{label}""#));
        }
        let msg = with("error", text, &[primary], "");
        translate(&msg, &mut Fake(Some(unit()))).unwrap()
    }

    fn builder_translated() -> Translated {
        at(
            "no method named `build` found for struct `GreetingPropsBuilder`",
            None,
            4,
            9,
        )
    }

    fn builder_twin(start: u32, end: u32) -> Translated {
        at(
            "this method takes 1 argument but 0 arguments were supplied",
            Some(MISSING_FIELD_LABEL),
            start,
            end,
        )
    }

    #[test]
    fn the_twin_filter_drops_the_untranslated_twin_that_follows() {
        let mut filter = TwinFilter::default();
        assert!(filter.admit(&builder_translated()));
        assert!(!filter.admit(&builder_twin(4, 9)));
    }

    #[test]
    fn a_twin_needs_the_same_generated_range() {
        let mut filter = TwinFilter::default();
        assert!(filter.admit(&builder_translated()));
        assert!(filter.admit(&builder_twin(5, 9)), "another range is kept");
    }

    #[test]
    fn a_users_own_diagnostic_at_the_same_position_is_kept() {
        let kept = suppress_untranslated_duplicates(vec![
            builder_translated(),
            at("use of deprecated function `Greeting`", None, 4, 9),
            at(
                "this method takes 1 argument but 0 arguments were supplied",
                Some("argument #1 is missing"),
                4,
                9,
            ),
            builder_twin(4, 9),
        ]);
        let messages: Vec<&str> = kept.iter().map(|t| t.diagnostic.message.as_str()).collect();
        assert_eq!(kept.len(), 3, "{messages:?}");
        assert!(messages.contains(&"use of deprecated function `Greeting`"));
    }

    #[test]
    fn the_batch_and_the_stream_agree() {
        let sequence = || {
            vec![
                builder_translated(),
                at("use of deprecated function `Greeting`", None, 4, 9),
                builder_twin(4, 9),
                builder_twin(5, 9),
            ]
        };
        let batch = suppress_untranslated_duplicates(sequence()).len();
        let mut filter = TwinFilter::default();
        let streamed = sequence().iter().filter(|t| filter.admit(t)).count();
        assert_eq!(batch, streamed);
        assert_eq!(batch, 3);
    }

    #[test]
    fn explanation_notes_name_only_the_codes_that_were_shown() {
        let note = |text: &str| {
            let msg = with("failure-note", text, &[], "");
            translate(&msg, &mut Fake(None)).unwrap()
        };
        let coded = |code: &str| {
            let mut shown = at("x", None, 4, 9);
            shown.code = Some(code.to_string());
            shown
        };
        let mut notes = ExplanationNotes::default();
        notes.record(&coded("E0308"));
        notes.record(&coded("E0599"));
        let list = notes
            .rewrite(note(
                "Some errors have detailed explanations: E0061, E0308, E0599.",
            ))
            .unwrap();
        assert_eq!(
            list.diagnostic.message,
            "Some errors have detailed explanations: E0308, E0599."
        );
        let more = notes
            .rewrite(note(
                "For more information about an error, try `rustc --explain E0061`.",
            ))
            .unwrap();
        assert_eq!(
            more.diagnostic.message,
            "For more information about an error, try `rustc --explain E0308`."
        );

        // Nothing left to explain: both notes disappear.
        let mut none = ExplanationNotes::default();
        assert!(none
            .rewrite(note(
                "Some errors have detailed explanations: E0061, E0277."
            ))
            .is_none());
        assert!(none
            .rewrite(note(
                "For more information about an error, try `rustc --explain E0061`."
            ))
            .is_none());
        assert!(none
            .rewrite(note(
                "For more information about this error, try `rustc --explain E0061`."
            ))
            .is_none());
    }

