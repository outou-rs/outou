//! Dropping what rustc says twice, and what it says about diagnostics
//! that were dropped.
//!
//! F21 (`docs/backend-leakage.md` row 27): a missing required prop
//! produces two diagnostics for one `.rsx` mistake. rustc reports the
//! translated one first (`use of deprecated method ...build: Missing
//! required field x`), then an untranslated `E0061` (`this method takes 1
//! argument but 0 arguments were supplied`) at the very same generated
//! range, whose label names the builder's `..._Missing_required_field_x`
//! type. The `E0061` adds only confusion, so it is dropped.
//!
//! Only that shape is a twin ([`Translated::is_builder_twin`]) and only at
//! the same generated byte range ([`Translated::raw_key`]): a user's own
//! diagnostic that happens to map to the same `.rsx` span (a `#[deprecated]`
//! warning on the component being used) is kept.
//!
//! The batch ([`suppress_untranslated_duplicates`]) and the stream
//! ([`TwinFilter`]) are one implementation, so they agree. Both rely on
//! rustc reporting the translated diagnostic first; if it did not, the
//! twin would be shown, which costs a duplicate and never a hard error.

use std::collections::{BTreeSet, HashSet};

use outou_sourcemap::Span;

use super::translate::Translated;

/// Remembers the generated ranges of translated diagnostics and says
/// whether a later diagnostic is the untranslated twin of one of them.
#[derive(Debug, Default)]
pub struct TwinFilter {
    translated: HashSet<(String, Span)>,
}

impl TwinFilter {
    /// Whether `candidate` should be shown. Records it when it is a
    /// translated diagnostic.
    pub fn admit(&mut self, candidate: &Translated) -> bool {
        let Some(key) = &candidate.raw_key else {
            return true;
        };
        if candidate.was_translated {
            self.translated.insert(key.clone());
            return true;
        }
        !(candidate.is_builder_twin && self.translated.contains(key))
    }
}

/// [`TwinFilter`] over a batch, in the order rustc reported it.
pub fn suppress_untranslated_duplicates(candidates: Vec<Translated>) -> Vec<Translated> {
    let mut filter = TwinFilter::default();
    candidates
        .into_iter()
        .filter(|candidate| filter.admit(candidate))
        .collect()
}

const SOME_ERRORS: &str = "Some errors have detailed explanations: ";
const MORE_INFO_MANY: &str = "For more information about an error, try `rustc --explain ";
const MORE_INFO_ONE: &str = "For more information about this error, try `rustc --explain ";

/// rustc ends a build with two notes naming the error codes it has
/// explanations for. After [`TwinFilter`] dropped a diagnostic, its code
/// must not be named there. This rewrites those notes to the codes that
/// were actually shown, and drops them when none were.
///
/// Feed it every diagnostic in the order they are printed
/// ([`ExplanationNotes::record`]), and every `failure-note` through
/// [`ExplanationNotes::rewrite`].
#[derive(Debug, Default)]
pub struct ExplanationNotes {
    shown: BTreeSet<String>,
    /// Codes the last `Some errors ...` note kept; `None` when there was
    /// no such note since the last `For more information` note.
    listed: Option<Vec<String>>,
}

impl ExplanationNotes {
    /// Notes that `shown` was printed.
    pub fn record(&mut self, shown: &Translated) {
        if shown.level == "failure-note" {
            return;
        }
        if let Some(code) = shown.code.as_deref().filter(|code| is_error_code(code)) {
            self.shown.insert(code.to_string());
        }
    }

    /// The note to print for `note`, or `None` to print nothing. Anything
    /// that is not one of rustc's explanation notes comes back unchanged.
    pub fn rewrite(&mut self, note: Translated) -> Option<Translated> {
        let text = note.diagnostic.message.clone();
        let rewritten = |mut note: Translated, message: String| {
            note.rustc_rendered = note.rustc_rendered.map(|_| format!("{message}\n"));
            note.diagnostic.message = message;
            Some(note)
        };
        if let Some(list) = text.strip_prefix(SOME_ERRORS) {
            let kept: Vec<String> = list
                .trim_end_matches('.')
                .split(", ")
                .filter(|code| self.shown.contains(*code))
                .map(str::to_string)
                .collect();
            self.listed = Some(kept.clone());
            return match kept.as_slice() {
                [] => None,
                [only] => rewritten(note, format!("{MORE_INFO_ONE}{only}`.")),
                many => rewritten(note, format!("{SOME_ERRORS}{}.", many.join(", "))),
            };
        }
        if let Some(code) = more_info_code(&text, MORE_INFO_MANY) {
            let listed = self.listed.take().unwrap_or_default();
            self.shown.clear();
            // A single remaining code was already named by the rewritten
            // `Some errors` note.
            if listed.len() < 2 {
                return None;
            }
            let first = listed.iter().find(|c| *c == code).unwrap_or(&listed[0]);
            return rewritten(note, format!("{MORE_INFO_MANY}{first}`."));
        }
        if let Some(code) = more_info_code(&text, MORE_INFO_ONE) {
            let keep = self.shown.contains(code);
            self.shown.clear();
            self.listed = None;
            return keep.then_some(note);
        }
        Some(note)
    }
}

fn more_info_code<'a>(text: &'a str, prefix: &str) -> Option<&'a str> {
    text.strip_prefix(prefix)?.strip_suffix("`.")
}

fn is_error_code(code: &str) -> bool {
    code.strip_prefix('E')
        .is_some_and(|digits| !digits.is_empty() && digits.chars().all(|c| c.is_ascii_digit()))
}
