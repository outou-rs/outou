//! rust-analyzer's standard error never reaches the editor by default (ledger
//! row 54): it carries generated Rust and `.generated` paths. Setting
//! `OUTOU_LSP_RA_LOG=1` passes it through unchanged for debugging.
//!
//! Drives the real `outou-lsp` binary with a fake rust-analyzer (a shell
//! script given through `OUTOU_RUST_ANALYZER`) that only writes to its
//! standard error and exits. outou-lsp then reports that it exited, which is
//! also checked: a dropped stderr must not leave a failure undiagnosable.

#![cfg(unix)]

use std::fs;
use std::io::Write;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicU32, Ordering};
use std::time::{Duration, Instant};

const NOISE: &str = "// Generated by Outou from src/main.rsx. Do not edit.\n\
use x::outou::__private::rsx! { __outou_key_0 } src/.generated/crate-root.rs";

fn frame(body: &serde_json::Value) -> Vec<u8> {
    let text = body.to_string();
    format!("Content-Length: {}\r\n\r\n{text}", text.len()).into_bytes()
}

fn fake_rust_analyzer(dir: &Path) -> std::path::PathBuf {
    let script = dir.join("fake-ra.sh");
    fs::write(&script, format!("#!/bin/sh\necho '{NOISE}' >&2\nexit 3\n")).unwrap();
    fs::set_permissions(&script, fs::Permissions::from_mode(0o755)).unwrap();
    script
}

/// Runs outou-lsp over a tiny `.rsx` crate and returns its standard error.
fn run_server(ra_log: Option<&str>) -> String {
    static COUNTER: AtomicU32 = AtomicU32::new(0);
    let dir = std::env::temp_dir().join(format!(
        "outou-lsp-ra-stderr-{}-{}",
        std::process::id(),
        COUNTER.fetch_add(1, Ordering::SeqCst)
    ));
    let _ = fs::remove_dir_all(&dir);
    let crate_dir = dir.join("app");
    fs::create_dir_all(crate_dir.join("src")).unwrap();
    fs::write(
        crate_dir.join("Cargo.toml"),
        "[package]\nname = \"app\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n\
         [[bin]]\nname = \"app\"\npath = \"src/.generated/crate-root.rs\"\n",
    )
    .unwrap();
    fs::write(crate_dir.join("src/main.rsx"), "fn main() {}\n").unwrap();
    let ra = fake_rust_analyzer(&dir);

    let mut command = Command::new(env!("CARGO_BIN_EXE_outou-lsp"));
    command
        .env("OUTOU_RUST_ANALYZER", &ra)
        .env_remove("OUTOU_LSP_RA_LOG")
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .stderr(Stdio::piped());
    if let Some(value) = ra_log {
        command.env("OUTOU_LSP_RA_LOG", value);
    }
    let mut child = command.spawn().unwrap();
    let mut stdin = child.stdin.take().unwrap();
    let uri = format!("file://{}", crate_dir.canonicalize().unwrap().display());
    let init = serde_json::json!({"jsonrpc":"2.0","id":1,"method":"initialize","params":{
        "processId": null, "capabilities": {},
        "workspaceFolders": [{"uri": uri, "name": "app"}]}});
    let initialized = serde_json::json!({"jsonrpc":"2.0","method":"initialized","params":{}});
    stdin.write_all(&frame(&init)).unwrap();
    stdin.write_all(&frame(&initialized)).unwrap();
    stdin.flush().unwrap();
    // Let the server see the fake rust-analyzer exit and forward its stderr.
    std::thread::sleep(Duration::from_millis(1500));
    let shutdown = serde_json::json!({"jsonrpc":"2.0","id":2,"method":"shutdown"});
    let exit = serde_json::json!({"jsonrpc":"2.0","method":"exit"});
    let _ = stdin.write_all(&frame(&shutdown));
    let _ = stdin.write_all(&frame(&exit));
    drop(stdin);

    let deadline = Instant::now() + Duration::from_secs(30);
    while child.try_wait().unwrap().is_none() {
        if Instant::now() > deadline {
            let _ = child.kill();
            panic!("outou-lsp did not exit");
        }
        std::thread::sleep(Duration::from_millis(50));
    }
    let output = child.wait_with_output().unwrap();
    let _ = fs::remove_dir_all(&dir);
    String::from_utf8_lossy(&output.stderr).into_owned()
}

#[test]
fn rust_analyzer_stderr_is_not_shown_by_default() {
    let stderr = run_server(None);
    for leaked in ["Generated by Outou", "__outou_", ".generated", "rsx!"] {
        assert!(!stderr.contains(leaked), "`{leaked}` leaked:\n{stderr}");
    }
    assert!(
        stderr.contains("rust-analyzer exited") && stderr.contains("OUTOU_LSP_RA_LOG"),
        "the failure must still be reported, with the way to investigate it:\n{stderr}"
    );
}

#[test]
fn rust_analyzer_stderr_is_passed_through_unchanged_when_asked() {
    let stderr = run_server(Some("1"));
    assert!(
        stderr.contains(NOISE),
        "rust-analyzer's stderr missing:\n{stderr}"
    );
}

#[test]
fn zero_does_not_turn_the_log_on() {
    let stderr = run_server(Some("0"));
    assert!(!stderr.contains("__outou_"), "{stderr}");
}
