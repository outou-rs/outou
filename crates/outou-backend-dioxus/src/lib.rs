/// What lowering needs besides the writer and the source text: the mode and
/// which options belong to which `<select value>` (issue #28).
#[derive(Clone, Copy)]
pub(crate) struct Cx<'a> {
    pub(crate) mode: Mode,
    pub(crate) selects: &'a SelectScan,
}

/// Root path through which generated code reaches the runtime.
pub const PRIVATE_PATH: &str = "::outou::__private";

/// File-level lint allow written at the top of a generated file that
/// needs it, for a mechanical lint that fires on codegen's own output
/// rather than on user code (issue #8's clippy requirement: generated
/// code must not pollute the user's `cargo clippy`). This crate never
/// widens an `allow` beyond what has actually been observed (`AGENTS.md`:
/// "Do not … add `allow` attributes to make them pass" applies to *this*
/// crate's own lints, not to the mechanical Rust it emits for users, which
/// issue #8 explicitly permits scoping an `allow` to).
///
/// Emitted only when [`Writer::marked`] is set after lowering (issue #8
/// fix list step 7) — i.e. only when some attribute island in this
/// specific file actually kept its synthesized braces
/// (`crate::attribute::bare_rust_expr`'s only-when-needed rule strips them
/// everywhere else). A nested-`rsx!` island prop (`icon={<span/>}`) is the
/// one shape that still needs them (stripping breaks `rsx!`'s own
/// parsing — `error: expected identifier` — and no universal brace-free
/// rewrite exists, `docs/backend-leakage.md` row 21).
///
/// This allow *is* file-scoped, and it *does* suppress `unused_braces` on
/// a user's own expression sitting anywhere else in the same file (a
/// corrected claim: an earlier version of this comment said the opposite,
/// disproved by `crates/outou-cli/tests/build_compile.rs`'s `take({ x })`
/// probe).
/// That is an accepted, narrow cost: only files that actually contain a
/// nested-JSX island prop carry the allow at all, and Phase 0 has no
/// narrower attribute-level `#[allow]` available in expression position.
const GENERATED_LINT_ALLOWS: &str = "#![allow(unused_braces)]\n";

/// The Dioxus backend.
#[derive(Debug, Default, Clone, Copy)]
pub struct DioxusBackend;

impl Backend for DioxusBackend {
    fn name(&self) -> &'static str {
        "dioxus"
    }

    fn generate(
        &self,
        parsed: &Parsed,
        source: &str,
        mode: Mode,
        opts: &GenerateOptions,
    ) -> Result<Generated, Error> {
        reject_syntax_errors_in_strict_mode(parsed, mode)?;

        // Whether `GENERATED_LINT_ALLOWS` belongs in the header can only
        // be known once the whole file has been lowered (some attribute
        // island might keep its braces), but the header has to be written
        // *before* the body for every byte offset the source map records
        // to be correct. A first, throwaway lowering pass answers that one
        // question — through the exact same code path as the real pass,
        // so it can never drift out of sync with what that pass actually
        // does — and only the second pass's writer is kept.
        let (selects, _) = outou_syntax::select::scan(&parsed.file);
        let cx = Cx {
            mode,
            selects: &selects,
        };
        let needs_lint_allow = {
            let mut probe = Writer::new(opts.generated_uri.clone(), opts.source_uri.clone());
            item::lower_items(
                &mut probe,
                source,
                &parsed.file.items,
                opts,
                cx,
                Span::new(0, source.len() as u32),
            );
            probe.marked()
        };

        let mut writer = Writer::new(opts.generated_uri.clone(), opts.source_uri.clone());
        writer.raw("// Generated by Outou from ");
        writer.raw(&opts.source_display);
        writer.raw(". Do not edit.\n");
        if needs_lint_allow {
            writer.raw(GENERATED_LINT_ALLOWS);
        }
        item::lower_items(
            &mut writer,
            source,
            &parsed.file.items,
            opts,
            cx,
            Span::new(0, source.len() as u32),
        );
        let (rust, source_map) = writer.finish();
        Ok(Generated { rust, source_map })
    }
}

