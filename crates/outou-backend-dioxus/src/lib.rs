    #[test]
    fn recovery_mode_replaces_a_name_less_element_with_the_placeholder() {
        // A fragment (`<>`) never recovers a tag name at all (grammar §10),
        // unlike e.g. `<div cl` which still knows its name is `div` and
        // lowers as an ordinary (if attribute-less) element.
        let source = "fn App() -> Element {\n    <>\n}\n";
        let generated = generate(source, Mode::Recovery).expect("recovery generation succeeds");
        assert!(generated
            .rust
            .contains("::outou::__private::recovery_element()"));
    }

    #[test]
    fn recovery_mode_still_lowers_a_named_but_unterminated_tag() {
        // `<User` interrupted by the enclosing block's `}` still knows its
        // name (`User`) and its (empty) attribute/child lists, so it
        // lowers as ordinary element syntax rather than the placeholder —
        // Dioxus's own `rsx!` closes an element with a synthesized `}`,
        // never a textual closing tag, so a missing closing tag never
        // prevents reconstruction (see `crate::element::is_broken`'s doc).
        let source = "fn App() -> Element {\n    <User\n}\n";
        let generated = generate(source, Mode::Recovery).expect("recovery generation succeeds");
        assert!(generated.rust.contains("User { }"), "{}", generated.rust);
        assert!(!generated.rust.contains("recovery_element"));
    }

    #[test]
    fn recovery_mode_closes_a_block_that_never_found_its_own_brace() {
        let source = "fn App() -> Element {\n    <div cl";
        let generated = generate(source, Mode::Recovery).expect("recovery generation succeeds");
        assert!(
            generated.rust.trim_end().ends_with('}'),
            "{}",
            generated.rust
        );
        let file = syn_parse(&generated.rust);
        assert!(file.is_ok(), "{:?}: {}", file.err(), generated.rust);
    }

    #[test]
    fn recovery_mode_keeps_the_symbol_for_a_function_with_no_body_at_all() {
        // MEDIUM-14, issue #6 fix list item 7: dropping the item entirely
        // removed `App` from the outline, from completion and from every
        // use site in the file — the opposite of what recovery mode
        // exists for. A placeholder keeps the name resolvable; its body
        // is never executed (`Mode::Recovery` output never reaches
        // `rustc` through `cargo build`).
        let source = "use outou::prelude::*;\n\nfn App(\n";
        let generated = generate(source, Mode::Recovery).expect("recovery generation succeeds");
        assert!(generated.rust.contains("fn App"), "{}", generated.rust);
        assert!(
            generated
                .rust
                .contains("::outou::__private::Element { ::outou::__private::recovery() }"),
            "{}",
            generated.rust
        );
        assert!(generated.rust.contains("use outou::prelude::*;"));
        let file = syn_parse(&generated.rust);
        assert!(file.is_ok(), "{:?}: {}", file.err(), generated.rust);
    }

    /// Minimal Rust-syntax check so recovery-mode tests don't need a `syn`
    /// dev-dependency just for this smoke test (the dedicated recovery
    /// integration test under `tests/` uses `syn` for a thorough check).
    fn syn_parse(rust: &str) -> Result<(), String> {
        let mut depth = 0i32;
        for byte in rust.bytes() {
            match byte {
                b'{' => depth += 1,
                b'}' => depth -= 1,
                _ => {}
            }
            if depth < 0 {
                return Err("unbalanced `}`".to_string());
            }
        }
        if depth == 0 {
            Ok(())
        } else {
            Err(format!("unbalanced braces, depth {depth}"))
        }
    }
