    fn first_module_span_start(parsed: &outou_syntax::Parsed) -> u32 {
        parsed
            .file
            .items
            .iter()
            .find_map(|item| match item {
                outou_syntax::ast::Item::Module(module) => Some(module.span.start),
                _ => None,
            })
            .expect("source has a top-level `mod` item")
    }

